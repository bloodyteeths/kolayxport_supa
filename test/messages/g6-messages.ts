/** Flattens the mirror into BUILD_PLAN §0.2 `newI18nKeys` rows (namespace = first segment). */
export function g6KeyRows(): { namespace: string; key: string; en: string; tr: string }[] {
  const out: { namespace: string; key: string; en: string; tr: string }[] = [];
  const walk = (en: Record<string, unknown>, tr: Record<string, unknown>, path: string[]) => {
    for (const [k, v] of Object.entries(en)) {
      if (v && typeof v === 'object') walk(v as Record<string, unknown>, tr[k] as Record<string, unknown>, [...path, k]);
      else out.push({ namespace: path[0], key: [...path.slice(1), k].join('.'), en: String(v), tr: String(tr[k]) });
    }
  };
  walk(G6_EN, G6_TR as unknown as Record<string, unknown>, []);
  return out;
}
