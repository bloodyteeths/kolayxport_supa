/** Flattens to `{ namespace: 'research', key, en, tr }[]` (key relative to the namespace). */
export function flattenKeys(en: Tree, tr: Tree, prefix = ''): { key: string; en: string; tr: string }[] {
  const out: { key: string; en: string; tr: string }[] = [];
  for (const [k, v] of Object.entries(en)) {
    const path = prefix ? `${prefix}.${k}` : k;
    const trv = (tr as Record<string, unknown>)[k];
    if (typeof v === 'string') out.push({ key: path, en: v, tr: typeof trv === 'string' ? trv : '' });
    else out.push(...flattenKeys(v, (trv && typeof trv === 'object' ? trv : {}) as Tree, path));
  }
  return out;
}
