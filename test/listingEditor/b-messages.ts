function merge(base: Tree, add: Tree): Tree {
  const out: Tree = { ...base };
  for (const [k, v] of Object.entries(add)) {
    const cur = out[k];
    out[k] = typeof v === 'object' && typeof cur === 'object' ? merge(cur, v) : (cur ?? v);
  }
  return out;
}

export type Locale = 'en' | 'tr';

export function withB(locale: Locale, extra?: Tree): Tree {
  const base = (locale === 'en' ? en : tr) as unknown as Tree;
  const le = (base.listingEditor as Tree | undefined) ?? {};
  const merged = merge(base, { listingEditor: merge(le, bListingEditor[locale]) });
  return extra ? merge(merged, extra) : merged;
}

/** Flat `{ key, en, tr }` list (the newI18nKeys payload). */
export function flatKeys(): Array<{ key: string; en: string; tr: string }> {
  const out: Array<{ key: string; en: string; tr: string }> = [];
  const walk = (e: Tree, r: Tree, prefix: string) => {
    for (const [k, v] of Object.entries(e)) {
      const key = prefix ? `${prefix}.${k}` : k;
      if (typeof v === 'string') out.push({ key, en: v, tr: String(r?.[k] ?? '') });
      else walk(v, (r?.[k] as Tree) ?? {}, key);
    }
  };
  walk(bListingEditor.en, bListingEditor.tr, '');
  return out;
}
