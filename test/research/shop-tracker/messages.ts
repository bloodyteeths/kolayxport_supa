export function flattenKeys(en: object, tr: object, prefix = ''): { key: string; en: string; tr: string }[] {
  const out: { key: string; en: string; tr: string }[] = [];
  for (const [k, v] of Object.entries(en)) {
    const key = prefix ? `${prefix}.${k}` : k;
    const trV = (tr as Record<string, unknown>)?.[k];
    if (v && typeof v === 'object') out.push(...flattenKeys(v as object, (trV ?? {}) as object, key));
    else out.push({ key, en: String(v), tr: typeof trV === 'string' ? trV : '' });
  }
  return out;
}
