function merge(base: Tree, extra: Tree): Tree {
  const out: Tree = { ...base };
  for (const [k, v] of Object.entries(extra)) {
    const cur = out[k];
    out[k] = typeof v === 'object' && cur && typeof cur === 'object' ? merge(cur, v) : v;
  }
  return out;
}

/** messages/<locale>.json with the M6b-D keys merged under `listingEditor`. */
export function withM6bD(locale: Locale): Tree {
  const base = (locale === 'en' ? en : tr) as unknown as Tree;
  return merge(base, { listingEditor: m6bdKeys[locale] });
}

/** Flattened `listingEditor.*` keys of this group (for newI18nKeys). */
export function flatM6bD(locale: Locale): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (t: Tree, prefix: string) => {
    for (const [k, v] of Object.entries(t)) {
      if (typeof v === 'string') out[`${prefix}${k}`] = v;
      else walk(v, `${prefix}${k}.`);
    }
  };
  walk(m6bdKeys[locale], 'listingEditor.');
  return out;
}
