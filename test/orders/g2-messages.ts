type Leaf = { namespace: string; key: string; en: string; tr: string };

/** Flattens G2_EN/G2_TR into the integrator's `newI18nKeys` shape (namespace = first segment). */
export function g2NewI18nKeys(): Leaf[] {
  const out: Leaf[] = [];
  const walk = (en: unknown, tr: unknown, path: string[]) => {
    if (typeof en === 'string') {
      out.push({ namespace: path[0], key: path.slice(1).join('.'), en, tr: String(tr ?? '') });
      return;
    }
    for (const k of Object.keys(en as object)) walk((en as Record<string, unknown>)[k], (tr as Record<string, unknown> | undefined)?.[k], [...path, k]);
  };
  walk(G2_EN, G2_TR, []);
  return out;
}
