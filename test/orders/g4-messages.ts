type Tree = { [k: string]: unknown };
function merge(base: Tree, extra: Tree): Tree {
  const out: Tree = { ...base };
  for (const [k, v] of Object.entries(extra)) {
    out[k] = v && typeof v === 'object' && !Array.isArray(v) && out[k] && typeof out[k] === 'object'
      ? merge(out[k] as Tree, v as Tree)
      : v;
  }
  return out;
}

/** messages/{locale}.json + the G4 keys (no-op once the integrator merged them). */
export function withG4(locale: 'en' | 'tr'): Tree {
  return merge((locale === 'en' ? en : tr) as Tree, (locale === 'en' ? G4_EN : G4_TR) as Tree);
}

/** Flattened `{ key, en, tr }` rows (for the newI18nKeys hand-off and the parity test). */
export function flattenG4(): { key: string; en: string; tr: string }[] {
  const rows: { key: string; en: string; tr: string }[] = [];
  const walk = (a: Tree, b: Tree, prefix: string) => {
    for (const [k, v] of Object.entries(a)) {
      const path = prefix ? `${prefix}.${k}` : k;
      if (v && typeof v === 'object') walk(v as Tree, (b?.[k] ?? {}) as Tree, path);
      else rows.push({ key: path, en: String(v), tr: String(b?.[k] ?? '') });
    }
  };
  walk(G4_EN as Tree, G4_TR as Tree, '');
  return rows;
}
